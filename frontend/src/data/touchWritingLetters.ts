/** Stroke-traced letters for TouchWritingStudio (viewBox 300×260). */

export interface LetterData {
  id: string;
  char: string;
  name: string;
  phonics: string;
  exampleWord: string;
  exampleTranslation: string;
  icon: string;
  strokeHintAr: string;
  strokeHintFr: string;
  strokesSvg: string[];
  dots: { x: number; y: number; order: number }[];
  direction: 'rtl' | 'ltr';
}

type XY = [number, number];

function letter(
  id: string,
  char: string,
  name: string,
  phonics: string,
  exampleWord: string,
  exampleTranslation: string,
  icon: string,
  hintAr: string,
  hintFr: string,
  strokesSvg: string[],
  dotsXY: XY[],
  direction: 'rtl' | 'ltr' = 'ltr',
): LetterData {
  return {
    id,
    char,
    name,
    phonics,
    exampleWord,
    exampleTranslation,
    icon,
    strokeHintAr: hintAr,
    strokeHintFr: hintFr,
    strokesSvg,
    dots: dotsXY.map(([x, y], i) => ({ x, y, order: i + 1 })),
    direction,
  };
}

function hintTrace(ar: string, fr: string): [string, string] {
  return [ar, fr];
}

