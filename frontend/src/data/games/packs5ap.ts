import type { GamePack, MazeCell } from './types';

/**
 * 5AP learning games (docs/v2-jeux-catalogue.md §7). Five levels per adventure, from a warm-up to
 * an expert challenge; every level is open. Numbers are written the Algerian way: decimal comma,
 * fractions as « a/b » (drawn stacked on screen). History dates follow the 5AP history lessons of
 * the catalog (data/courses/5AP/history_geo.ts).
 */

const ok = (t: string): MazeCell => ({ t, ok: true });
const no = (t: string, whyAr: string): MazeCell => ({ t, ok: false, whyAr });

/** « 3/4 », « 0,75 », « 75% » → 0.75 (same reading as the content test). */
function valueOf(t: string): number {
  const fraction = /^(\d+)\/(\d+)$/.exec(t);
  if (fraction) return Number(fraction[1]) / Number(fraction[2]);
  if (t.endsWith('%')) return Number(t.slice(0, -1).replace(',', '.')) / 100;
  return Number(t.replace(',', '.'));
}
const same = (a: number, b: number) => Math.abs(a - b) < 1e-9;
/** « 3/5 = 0,6 », « 1/3 ≈ 0,333 », or the stone itself when it is already a decimal. */
function shown(t: string): string {
  const v = valueOf(t);
  const rounded = Math.round(v * 1000) / 1000;
  const dec = String(rounded).replace('.', ',');
  if (dec === t) return t;
  return `${t} ${same(rounded, v) ? '=' : '≈'} ${dec}`;
}
/**
 * A maths maze from its stones: each stone is checked against the rule, and every wrong stone gets
 * Didou's explanation computed from its value — never a hand-typed number that could be wrong.
 */
function ruleMaze(rows: string[][], isOk: (v: number) => boolean, why: (t: string, v: number) => string): MazeCell[][] {
  return rows.map((row) => row.map((t) => (isOk(valueOf(t)) ? ok(t) : no(t, why(t, valueOf(t))))));
}

