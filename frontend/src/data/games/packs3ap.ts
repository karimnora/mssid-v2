import type { GamePack, MazeCell, MemoryRound, OrderRound } from './types';

/**
 * 3AP learning games (docs/v2-jeux-catalogue.md §4). 3AP is the first year of English and French:
 * the language packs read every card aloud in that language (`cardLang`) while Didou explains in
 * Arabic. Arabic follows the 3AP grammar lessons (جملة اسمية وفعلية، الماضي والمضارع والأمر، همزة
 * الوصل والقطع…), maths the numbers below 100 000, money, measures and time. Ten levels each.
 */

const ok = (t: string): MazeCell => ({ t, ok: true });
const no = (t: string, whyAr: string): MazeCell => ({ t, ok: false, whyAr });

type Pair = MemoryRound['pairs'][number];
/** An English word and its picture (or digit); `meaningAr` is what Didou says it means. */
const word = (en: string, picture: string, meaningAr: string): Pair => ({
  id: en.replace(/\s/g, '-'),
  a: en,
  b: picture,
  valueAr: meaningAr,
  linkAr: `«${en}» تَعْنِي ${meaningAr}. ${picture}`,
});
const EN_MISMATCH = '«{a}» تَعْنِي {va}، وَ«{b}» هِيَ {vb}: لَيْسَتَا تَوْأَمَيْنِ.';

type Card = OrderRound['cards'][number];
/** A number card: its text is drawn left-to-right, its rank is its value. */
const n = (text: string, rank: number, keyAr: string, emoji = '🎟️'): Card => ({ id: `n${rank}`, textAr: text, emoji, keyAr, rank });
const NUMBER_WRONG = '«{card}» ({key}) أَكْبَرُ مِنْ عَدَدٍ آخَرَ مَا زَالَ يَنْتَظِرُ.';

/** French maze stone that does not follow the rule, with Didou's reason. */
const fr = (t: string, whyAr: string) => no(t, whyAr);

