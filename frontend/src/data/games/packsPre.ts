/**
 * Preschool learning games (3-5 years, docs/v2-jeux-catalogue.md). « Zero text »: every card is a
 * picture, Didou says every rule and reads every card when tapped (`young`), targets are 72 px.
 * Each level belongs to a real module of the preschool catalog (`PRESCHOOL_MODULES` id). The first
 * levels ask to find the same picture; later ones ask to link two things that go together.
 */

const ok = (t: string): MazeCell => ({ t, ok: true });
const no = (t: string, whyAr: string): MazeCell => ({ t, ok: false, whyAr });

const PAIR_MISMATCH = 'هُنَا {va}، وَهُنَاكَ {vb}: لَيْسَا مَعاً.';

type Pair = MemoryRound['pairs'][number];
/** The same picture twice: once with its name, once alone. */
const twin = (id: string, emoji: string, nameAr: string): Pair => ({ id, a: `${emoji} ${nameAr}`, b: emoji, valueAr: nameAr, linkAr: `أَحْسَنْتَ! ${nameAr} وَ${nameAr}: صُورَتَانِ مُتَشَابِهَتَانِ.` });
/** Two pictures that go together (the rabbit and its carrot…). */
const link = (id: string, a: string, b: string, valueAr: string, linkAr: string): Pair => ({ id, a, b, valueAr, linkAr });

type Wagon = OrderRound['cards'][number];
const NUMBER_WORDS = ['صِفْرٌ', 'وَاحِدٌ', 'اثْنَانِ', 'ثَلَاثَةٌ', 'أَرْبَعَةٌ', 'خَمْسَةٌ', 'سِتَّةٌ', 'سَبْعَةٌ', 'ثَمَانِيَةٌ', 'تِسْعَةٌ', 'عَشَرَةٌ'];
/** A wagon carrying `n` pictures, with its digit as the big sign. */
const count = (n: number, emoji: string): Wagon => ({ id: `n${n}`, textAr: emoji.repeat(n), emoji: String(n), keyAr: NUMBER_WORDS[n], rank: n });
/** A wagon showing its digit only (the child reads the number). */
const digit = (n: number, emoji: string): Wagon => ({ id: `d${n}`, textAr: NUMBER_WORDS[n], emoji: `${emoji}${n}`, keyAr: NUMBER_WORDS[n], rank: n });
const COUNT_WRONG = 'هَذِهِ العَرَبَةُ فِيهَا {key} «{card}»، وَهُنَاكَ عَرَبَةٌ فِيهَا أَقَلُّ مَا زَالَتْ تَنْتَظِرُ.';
const DIGIT_WRONG = '«{card}» ({key}) كَبِيرٌ، وَهُنَاكَ عَدَدٌ أَصْغَرُ مِنْهُ مَا زَالَ يَنْتَظِرُ.';
