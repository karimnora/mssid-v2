const ok = (t: string): MazeCell => ({ t, ok: true });
const no = (t: string, whyAr: string): MazeCell => ({ t, ok: false, whyAr });

/** « 3 × 4 », « 38 + 12 », « 60 − 10 » or « 345 » → its value (× before + and −). */
function valueOf(t: string): number {
  return t
    .replace(/\s/g, '')
    .split(/(?=[+−])/)
    .reduce((total, part) => {
      const sign = part.startsWith('−') ? -1 : 1;
      return total + sign * part.replace(/^[+−]/, '').split('×').reduce((p, f) => p * Number(f), 1);
    }, 0);
}
/** « 3 × 4 = 12 », or the number itself. */
const shown = (t: string) => (/[×+−]/.test(t) ? `${t} = ${valueOf(t)}` : t);
/** A maths maze from its stones: Didou's explanation of each wrong stone is computed from its value. */
function ruleMaze(rows: string[][], isOk: (v: number) => boolean, why: (t: string, v: number) => string): MazeCell[][] {
  return rows.map((row) => row.map((t) => (isOk(valueOf(t)) ? ok(t) : no(t, why(t, valueOf(t))))));
}

type Pair = MemoryRound['pairs'][number];
/** A calculation and its result: « 2 × 3 » ↔ « 6 ». */
const fact = (a: string, b: string, linkAr?: string): Pair => {
  const v = valueOf(a);
  return { id: `${a}-${b}`.replace(/\s/g, ''), a, b, valueAr: String(v), linkAr: linkAr ?? `${a} = ${v}.` };
};

