const ok = (t: string): MazeCell => ({ t, ok: true });
const no = (t: string, whyAr: string): MazeCell => ({ t, ok: false, whyAr });

/** « 6 × 7 », « 42 ÷ 7 », « 5 × 3 + 2 » or « 56 » → its value (× and ÷ before + and −). */
function valueOf(t: string): number {
  return t
    .replace(/\s/g, '')
    .split(/(?=[+−])/)
    .reduce((total, part) => {
      const sign = part.startsWith('−') ? -1 : 1;
      const product = part
        .replace(/^[+−]/, '')
        .split(/(?=[×÷])/)
        .reduce((p, f) => (f.startsWith('÷') ? p / Number(f.slice(1)) : p * Number(f.replace('×', ''))), 1);
      return total + sign * product;
    }, 0);
}

type Pair = MemoryRound['pairs'][number];
/** A calculation and its result (or two calculations with the same result). */
const fact = (a: string, b: string): Pair => {
  const v = valueOf(a);
  return { id: `${a}=${b}`.replace(/\s/g, ''), a, b, valueAr: String(v), linkAr: `${a} = ${b === String(v) ? v : `${b} = ${v}`}.` };
};
/** Two writings of the same fraction. */
const frac = (a: string, b: string, valueAr: string, linkAr: string): Pair => ({ id: `${a}~${b}`.replace(/\//g, '-'), a, b, valueAr, linkAr });

type Step = OrderRound['cards'][number];
const step = (id: string, textAr: string, emoji: string, rank: number): Step => ({ id, textAr, emoji, keyAr: `المَرْحَلَةُ ${rank}`, rank });
const STEP_WRONG = '«{card}» هِيَ {key}، وَهُنَاكَ مَرْحَلَةٌ تَأْتِي قَبْلَهَا.';

type CardAr = { id: string; textAr: string; bin: string; whyAr: string };
const card = (id: string, textAr: string, bin: string, whyAr: string): CardAr => ({ id, textAr, bin, whyAr });

/** English maze stone that does not follow the rule, with Didou's reason in Arabic. */
const en = (t: string, whyAr: string) => no(t, whyAr);

