function hasLevels(exercises: ProgressiveExercise[] | undefined, levels: PedagogicalLevel[]): boolean {
  const have = new Set((exercises || []).map((ex) => ex.level));
  return levels.every((lv) => have.has(lv));
}

export function applyHomeworkLinkedBoost(lessons: CourseLesson[]): CourseLesson[] {
  return lessons.map((lesson) => {
    const extraQuiz = HOMEWORK_QUIZ_BOOST[lesson.id];
    const extraProg = HOMEWORK_PROG_BOOST[lesson.id];
    if (!extraQuiz && !extraProg) return lesson;

    let quiz = lesson.quiz || [];
    if (extraQuiz && quiz.length < 6) {
      const missing = 6 - quiz.length;
      quiz = [...quiz, ...extraQuiz.slice(0, missing)];
    }

    let progressiveExercises = lesson.progressiveExercises;
    if (extraProg && !hasLevels(progressiveExercises, [1, 2, 3])) {
      progressiveExercises = [...(progressiveExercises || []), ...extraProg];
    }

    return { ...lesson, quiz, progressiveExercises };
  });
}
