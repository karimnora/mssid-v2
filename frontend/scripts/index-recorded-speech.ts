import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { recordedSpeechKey } from '../src/utils/recordedSpeechKey';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const docs = resolve(root, 'docs/audio-v1');
type Clip = { texte: string; spokenText?: string; fichier: string; duration: number; sha256: string };
type Entry = { src: string; durationMs: number };
const catalog: Record<string, Record<string, Entry>> = { ar: {}, fr: {}, en: {} };
const sources = new Set<string>();
for (const file of readdirSync(docs).filter(name => /^enregistrements-.*\.json$/.test(name)).sort()) {
  const metadata = JSON.parse(readFileSync(resolve(docs, file), 'utf8'));
  for (const language of ['ar', 'fr', 'en']) {
    for (const clip of (metadata[language]?.clips ?? []) as Clip[]) {
      const src = `/sounds/preschool/${language}/${clip.fichier}`;
      const path = resolve(root, 'frontend/public', src.slice(1));
      if (!existsSync(path)) throw new Error(`Missing recording: ${src}`);
      const digest = createHash('sha256').update(readFileSync(path)).digest('hex');
      if (digest !== clip.sha256) throw new Error(`Recording integrity mismatch: ${src}`);
      if (!(clip.duration > 0)) throw new Error(`Missing duration: ${src}`);
      // An explicitly named standalone mark also reuses the exact spoken label elsewhere.
      for (const text of [clip.texte, ...(clip.spokenText ? [clip.spokenText] : [])]) {
        const key = recordedSpeechKey(text);
        catalog[language][key] ??= { src, durationMs: Math.round(clip.duration * 1000) };
      }
      sources.add(src);
    }
  }
}
writeFileSync(resolve(root, 'frontend/src/data/recordedSpeechCatalog.ts'),
  '// Generated by scripts/index-recorded-speech.ts. Do not edit by hand.\n' +
  'export const RECORDED_SPEECH_CATALOG: Record<string, Record<string, { src: string; durationMs: number }>> = ' +
  JSON.stringify(catalog, null, 2) + ';\n');

const available: unknown[] = [];
const requests: Record<string, { language: string; text: string; targets: string[] }> = {};
for (const folder of readdirSync(resolve(docs, 'prochains')).filter(name => /^\d\d-/.test(name)).sort()) {
  for (const language of ['ar', 'fr', 'en']) {
    const plan = resolve(docs, 'prochains', folder, `${language}-decoupage.json`);
    if (!existsSync(plan)) continue;
    for (const cue of JSON.parse(readFileSync(plan, 'utf8'))) {
      const key = recordedSpeechKey(cue.texte);
      const existing = Object.hasOwn(catalog[language], key) ? catalog[language][key] : undefined;
      const target = `${folder}/${language}/${cue.fichier}`;
      if (existing) available.push({ target, language, text: cue.texte, ...existing });
      else {
        const requestKey = JSON.stringify([language, key]);
        requests[requestKey] ??= { language, text: cue.texte, targets: [] };
        requests[requestKey].targets.push(target);
      }
    }
  }
}
const pending = Object.values(requests);
const pendingTargets = pending.reduce((sum, item) => sum + item.targets.length, 0);
const summary = { sourceRecordings: sources.size,
  uniqueRecordedPhrases: Object.values(catalog).reduce((sum, items) => sum + Object.keys(items).length, 0),
  reusablePlanEntries: available.length, pendingPlanEntries: pendingTargets,
  uniquePendingGenerations: pending.length, duplicateGenerationsAvoided: pendingTargets - pending.length };
writeFileSync(resolve(docs, 'REUTILISATION-AUDIO.json'), JSON.stringify({ summary, available, pending }, null, 2) + '\n');
console.log(JSON.stringify(summary));
