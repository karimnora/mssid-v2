import type { PrimaryGrade } from '../src/types';
import { COMPETENCES, getCompetence } from '../src/data/competences';

export type CahierFigure = 'square-circle' | 'two-dots' | 'stars-5';

export interface CahierExercise {
  promptAr: string;
  lines: number;
  figure?: CahierFigure;
}

export interface CompetenceCahier {
  competenceId: string;
  grade: PrimaryGrade;
  titleAr: string;
  domainAr: string;
  exercises: CahierExercise[];
  versoAr: string[];
}

function sheet(
  competenceId: string,
  exercises: CahierExercise[],
  versoAr: string[],
): CompetenceCahier {
  const competence = getCompetence(competenceId);
  if (!competence) {
    throw new Error(`Unknown competence ${competenceId}`);
  }
  return {
    competenceId,
    grade: competence.grade,
    titleAr: competence.labelAr,
    domainAr: competence.domainAr,
    exercises,
    versoAr,
  };
}

