-- V3: soft email verification (SEC-08). Never blocks app usage — see User.emailVerified /
-- EmailVerificationService — this is a UI reminder + a prerequisite for future features (password
-- reset) that genuinely need a confirmed address, not an access gate.

ALTER TABLE public.users
    ADD COLUMN email_verified boolean NOT NULL DEFAULT false;

CREATE TABLE public.email_verification_codes (
    id bigint NOT NULL,
    code_hash character varying(64) NOT NULL,
    user_id bigint NOT NULL,
    expires_at timestamp(6) without time zone NOT NULL,
    consumed boolean NOT NULL,
    created_at timestamp(6) without time zone NOT NULL
);

ALTER TABLE public.email_verification_codes ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.email_verification_codes_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY public.email_verification_codes
    ADD CONSTRAINT email_verification_codes_pkey PRIMARY KEY (id);

ALTER TABLE ONLY public.email_verification_codes
    ADD CONSTRAINT fk_email_verification_codes_user FOREIGN KEY (user_id) REFERENCES public.users(id);

CREATE INDEX idx_email_verification_codes_user_id ON public.email_verification_codes (user_id);
