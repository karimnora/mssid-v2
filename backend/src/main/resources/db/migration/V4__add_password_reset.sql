-- V4: "mot de passe oublié" (SEC-09) — anticipated in V3's comment as a natural follow-up once
-- transactional email (Resend) was wired up. Same shape as email_verification_codes: a hashed,
-- single-use, time-limited 6-digit code, never the raw code at rest.

CREATE TABLE public.password_reset_codes (
    id bigint NOT NULL,
    code_hash character varying(64) NOT NULL,
    user_id bigint NOT NULL,
    expires_at timestamp(6) without time zone NOT NULL,
    consumed boolean NOT NULL,
    created_at timestamp(6) without time zone NOT NULL
);

ALTER TABLE public.password_reset_codes ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.password_reset_codes_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY public.password_reset_codes
    ADD CONSTRAINT password_reset_codes_pkey PRIMARY KEY (id);

ALTER TABLE ONLY public.password_reset_codes
    ADD CONSTRAINT fk_password_reset_codes_user FOREIGN KEY (user_id) REFERENCES public.users(id);

CREATE INDEX idx_password_reset_codes_user_id ON public.password_reset_codes (user_id);
