-- V2: refresh_tokens table backing RefreshTokenService (SEC-06). Follows the same IDENTITY-column
-- style Hibernate already generates for the most recent entities in V1 (users, roles, subscriptions).

CREATE TABLE public.refresh_tokens (
    id bigint NOT NULL,
    token_hash character varying(64) NOT NULL,
    user_id bigint NOT NULL,
    expires_at timestamp(6) without time zone NOT NULL,
    revoked boolean NOT NULL,
    created_at timestamp(6) without time zone NOT NULL
);

ALTER TABLE public.refresh_tokens ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.refresh_tokens_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY public.refresh_tokens
    ADD CONSTRAINT refresh_tokens_pkey PRIMARY KEY (id);

ALTER TABLE ONLY public.refresh_tokens
    ADD CONSTRAINT refresh_tokens_token_hash_key UNIQUE (token_hash);

ALTER TABLE ONLY public.refresh_tokens
    ADD CONSTRAINT fk_refresh_tokens_user FOREIGN KEY (user_id) REFERENCES public.users(id);

CREATE INDEX idx_refresh_tokens_user_id ON public.refresh_tokens (user_id);
